"""Unprivileged, disposable PG18 cluster. Only manifest + dump cross this boundary."""
import json
import os
from pathlib import Path
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import (ENV, PG, TABLES_SQL, counts_sql, read_frame, require, run, safe_main)


def compare_counts(expected, actual):
    require(expected == actual, "count_mismatch")


def restore(stream):
    # Neither the live socket nor production credentials are visible in this unit.
    require(os.geteuid() != 0, "unsafe_restore_user")
    env = {**ENV, "PGUSER": "skm_site_restore"}
    with tempfile.TemporaryDirectory(prefix="check-", dir="/run/skm-site-restore") as tmp:
        work = Path(tmp)
        dump = work / "database.dump"
        manifest = read_frame(stream, dump)
        data, socket = work / "data", work / "socket"
        socket.mkdir(mode=0o700)
        run([PG + "initdb", "-D", str(data), "--no-locale", "--encoding=UTF8",
             "--auth-local=trust", "--auth-host=reject", "--username=skm_site_restore"], env=env)
        # These paths are generated by tempfile, not derived from archive/manifest input.
        (data / "postgresql.conf").write_text(
            "listen_addresses=''\nunix_socket_directories='" + str(socket) + "'\n"
            "unix_socket_permissions=0700\nshared_buffers=32MB\nmax_connections=5\n"
            "max_worker_processes=0\nmax_parallel_workers=0\nfsync=off\n"
            "log_min_messages=panic\nlogging_collector=off\n", encoding="utf-8")
        try:
            run([PG + "pg_ctl", "-D", str(data), "-l", str(work / "postgres.log"),
                 "-w", "-t", "20", "start"], env=env, timeout=30)
            connection = ["-h", str(socket), "-U", "skm_site_restore"]
            run([PG + "createdb", *connection, "skm_site_restore"], env=env)
            run([PG + "pg_restore", *connection, "-d", "skm_site_restore", "--no-owner",
                 "--no-acl", "--exit-on-error", "--no-password", str(dump)], env=env, timeout=360)
            psql = [PG + "psql", "-X", "-qAt", "-v", "ON_ERROR_STOP=1", *connection,
                    "-d", "skm_site_restore"]
            tables = json.loads(run(psql, input=TABLES_SQL.encode(), env=env))
            actual = json.loads(run(psql, input=counts_sql(tables).encode(), env=env))
            compare_counts(manifest["counts"], actual)
            run([PG + "pg_amcheck", *connection, "-d", "skm_site_restore", "--install-missing",
                 "--heapallindexed", "--checkunique", "--parent-check", "--rootdescend",
                 "--jobs=1", "--no-password"], env=env, timeout=240)
        finally:
            # Also stop after a partially failed pg_ctl start. systemd kills the cgroup as fallback.
            run([PG + "pg_ctl", "-D", str(data), "-m", "immediate", "-w", "-t", "15", "stop"],
                env=env, timeout=25)


def main():
    require(len(sys.argv) == 1)
    os.umask(0o077)
    restore(sys.stdin.buffer)
    sys.stdout.buffer.write(b'{"status":"passed","counts_verified":true,"amcheck":"passed"}\n')


if __name__ == "__main__":
    sys.exit(safe_main(main))
